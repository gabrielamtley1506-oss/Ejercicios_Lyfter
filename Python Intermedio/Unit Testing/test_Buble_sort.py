from Bubble_sort import bubble_sort

def test_sort_with_small_list_returns_list_sorted():
    #Arrange
    list_input = [9, 5, 7, 10]
    #Act
    result = bubble_sort(list_input)
    #Assert
    assert result == [5, 7, 9, 10]


